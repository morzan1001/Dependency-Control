def resolve_detector_name(raw: object) -> str | None:
    """The detector name for a stored ``details.detector``; None when it is not a known ordinal."""
    if isinstance(raw, bool) or not isinstance(raw, (int, str)):
        return None
    text = str(raw).strip()
    if not text.isdigit():
        return None
    return DETECTOR_TYPE_NAMES.get(int(text))
